
import streamlit as st
import pandas as pd
import joblib

from sklearn.metrics import (
    mean_absolute_error,
    mean_squared_error,
    r2_score
)

# --------------------------------------------------
# 1. Page Configuration
# --------------------------------------------------
st.set_page_config(
    page_title="EV Battery Health Dashboard",
    page_icon="🔋",
    layout="wide"
)

# --------------------------------------------------
# 2. Dashboard Title
# --------------------------------------------------
st.title("🔋 EV Battery Cell Degradation Prediction")

st.write(
    "Machine-learning-based monitoring and prediction "
    "of Electric Vehicle battery State of Health (SOH)."
)

st.divider()

# --------------------------------------------------
# 3. Load Dataset and Model
# --------------------------------------------------
@st.cache_data
def load_data():
    return pd.read_csv("battery_dataset.csv")


@st.cache_resource
def load_model():
    return joblib.load("battery_soh_model.pkl")


@st.cache_data
def load_simulink_data():
    return pd.read_csv("simulink_battery_data.csv")


try:

    battery_data = load_data()
    model = load_model()

    st.success("Battery dataset and ML model loaded successfully!")

    # --------------------------------------------------
    # 4. Select Battery Cell
    # --------------------------------------------------
    st.subheader("Select Battery Cell")

    cell_ids = sorted(battery_data["CellID"].unique())

    selected_cell = st.selectbox(
        "Choose a cell ID",
        cell_ids
    )

    cell_data = battery_data[
        battery_data["CellID"] == selected_cell
    ].sort_values("Cycle")

    if cell_data.empty:
        st.warning("No data available for this battery cell.")
        st.stop()

    latest = cell_data.iloc[-1]
    soh = float(latest["SOH"])

    # --------------------------------------------------
    # 5. Battery Information
    # --------------------------------------------------
    st.subheader("Battery Information")

    col1, col2, col3 = st.columns(3)

    col1.metric(
        "Selected Cell",
        int(selected_cell)
    )

    col2.metric(
        "Latest SOH",
        f"{soh:.2f}%"
    )

    col3.metric(
        "Latest Capacity",
        f"{latest['Capacity']:.3f} Ah"
    )

    # --------------------------------------------------
    # 6. Battery Health Status
    # --------------------------------------------------
    st.subheader("Battery Health Status")

    if soh >= 90:
        st.success("Healthy — SOH is 90% or above.")

    elif soh >= 80:
        st.warning(
            "Moderate Degradation — SOH is between 80% and 90%."
        )

    else:
        st.error(
            "High Degradation — SOH is below 80%."
        )

    st.progress(
        max(
            0.0,
            min(1.0, soh / 100.0)
        )
    )

    st.caption(
        "These are illustrative project thresholds, "
        "not universal battery safety limits."
    )

    # --------------------------------------------------
    # 7. Selected Cell SOH Graph
    # --------------------------------------------------
    st.subheader("Battery State of Health Over Cycles")

    st.line_chart(
        cell_data.set_index("Cycle")[["SOH"]]
    )

    # --------------------------------------------------
    # 8. Machine Learning Prediction
    # --------------------------------------------------
    st.subheader("Machine Learning Prediction")

    features = [
        "Voltage",
        "Current",
        "Temperature",
        "Cycle"
    ]

    input_data = cell_data[
        features
    ].iloc[[-1]]

    predicted_soh = float(
        model.predict(input_data)[0]
    )

    pred_col1, pred_col2 = st.columns(2)

    pred_col1.metric(
        "Actual Simulated SOH",
        f"{soh:.2f}%"
    )

    pred_col2.metric(
        "Predicted SOH",
        f"{predicted_soh:.2f}%"
    )

    st.caption(
        "Prediction is generated by the trained Random Forest "
        "model using the selected cell's latest simulated measurements."
    )

    # --------------------------------------------------
    # 9. Measurement Data Table
    # --------------------------------------------------
    st.subheader("Cell Measurement Data")

    st.dataframe(
        cell_data,
        use_container_width=True
    )

    # --------------------------------------------------
    # 10. Download Selected Cell Data
    # --------------------------------------------------
    st.subheader("Download Results")

    csv_data = cell_data.to_csv(
        index=False
    ).encode("utf-8")

    st.download_button(
        label="Download Cell Data as CSV",
        data=csv_data,
        file_name=f"battery_cell_{selected_cell}_data.csv",
        mime="text/csv"
    )

    # --------------------------------------------------
    # 11. Compare SOH Across All Cells
    # --------------------------------------------------
    st.divider()

    st.subheader(
        "SOH Comparison Across All Battery Cells"
    )

    soh_comparison = battery_data.pivot(
        index="Cycle",
        columns="CellID",
        values="SOH"
    ).sort_index()

    soh_comparison.columns = [
        f"Cell {int(cell_id)}"
        for cell_id in soh_comparison.columns
    ]

    st.line_chart(
        soh_comparison
    )

    st.caption(
        "Each line represents one simulated battery cell. "
        "A faster downward trend indicates faster simulated "
        "degradation in this dataset."
    )

    # --------------------------------------------------
    # 12. Model Performance Evaluation
    # --------------------------------------------------
    st.divider()

    st.subheader(
        "Machine Learning Model Performance"
    )

    st.write(
        "Evaluation on unseen simulated cells. "
        "Cells 1–15 are used for training and Cells 16–20 "
        "are reserved for testing."
    )

    train_data = battery_data[
        battery_data["CellID"] <= 15
    ]

    test_data = battery_data[
        battery_data["CellID"] > 15
    ]

    if train_data.empty or test_data.empty:

        st.warning(
            "The dataset does not contain both training cells "
            "and test cells for this evaluation."
        )

    else:

        X_train = train_data[features]
        y_train = train_data["SOH"]

        X_test = test_data[features]
        y_test = test_data["SOH"]

        # Recreate the evaluated model
        evaluation_model = joblib.load(
            "battery_soh_model.pkl"
        )

        evaluation_model.fit(
            X_train,
            y_train
        )

        y_pred = evaluation_model.predict(
            X_test
        )

        mae = mean_absolute_error(
            y_test,
            y_pred
        )

        rmse = mean_squared_error(
            y_test,
            y_pred
        ) ** 0.5

        r2 = r2_score(
            y_test,
            y_pred
        )

        metric1, metric2, metric3 = st.columns(3)

        metric1.metric(
            "MAE",
            f"{mae:.4f}%"
        )

        metric2.metric(
            "RMSE",
            f"{rmse:.4f}%"
        )

        metric3.metric(
            "R² Score",
            f"{r2:.4f}"
        )

        st.write(
            f"Test samples: {len(y_test)} | "
            f"Test cells: "
            f"{sorted(test_data['CellID'].unique())}"
        )

        st.caption(
            "MAE and RMSE are prediction error measures; lower values "
            "are generally better. R² measures how well predictions "
            "explain variation in SOH. These metrics describe the "
            "synthetic dataset, not real-world battery performance."
        )

    # --------------------------------------------------
    # 13. Simulink Simulation Results
    # --------------------------------------------------
    st.divider()

    st.subheader(
        "MATLAB/Simulink Simulation Results"
    )

    st.write(
        "Battery voltage, current, temperature, and SOH "
        "generated from the MATLAB/Simulink simulation."
    )

    # Load Simulink CSV
    simulink_data = load_simulink_data()

    # --------------------------------------------------
    # Simulation Summary
    # --------------------------------------------------
    st.write("### Simulation Summary")

    sim_col1, sim_col2, sim_col3, sim_col4 = st.columns(4)

    sim_col1.metric(
        "Initial Voltage",
        f"{simulink_data['Voltage'].iloc[0]:.2f} V"
    )

    sim_col2.metric(
        "Final Voltage",
        f"{simulink_data['Voltage'].iloc[-1]:.2f} V"
    )

    sim_col3.metric(
        "Initial SOH",
        f"{simulink_data['SOH'].iloc[0]:.2f}%"
    )

    sim_col4.metric(
        "Final SOH",
        f"{simulink_data['SOH'].iloc[-1]:.2f}%"
    )

    # --------------------------------------------------
    # Simulated SOH
    # --------------------------------------------------
    st.write("### Simulated Battery SOH")

    st.line_chart(
        simulink_data.set_index("Time")[["SOH"]]
    )

    # --------------------------------------------------
    # Simulated Voltage
    # --------------------------------------------------
    st.write("### Simulated Battery Voltage")

    st.line_chart(
        simulink_data.set_index("Time")[["Voltage"]]
    )

    # --------------------------------------------------
    # Simulated Temperature
    # --------------------------------------------------
    st.write("### Simulated Battery Temperature")

    st.line_chart(
        simulink_data.set_index("Time")[["Temperature"]]
    )

    # --------------------------------------------------
    # Simulated Current
    # --------------------------------------------------
    st.write("### Simulated Battery Current")

    st.line_chart(
        simulink_data.set_index("Time")[["Current"]]
    )

    # --------------------------------------------------
    # Simulink Data Table
    # --------------------------------------------------
    st.write("### Simulink Measurement Data")

    st.dataframe(
        simulink_data,
        use_container_width=True
    )

    # --------------------------------------------------
    # Download Simulink Data
    # --------------------------------------------------
    st.write("### Download Simulation Data")

    sim_csv = simulink_data.to_csv(
        index=False
    ).encode("utf-8")

    st.download_button(
        label="Download Simulink Simulation Data",
        data=sim_csv,
        file_name="simulink_battery_data.csv",
        mime="text/csv"
    )

    # --------------------------------------------------
    # 14. Project Information
    # --------------------------------------------------
    st.divider()

    st.subheader(
        "About This Project"
    )

    st.write(
        "This project simulates individual lithium-ion battery "
        "cell degradation and uses a Random Forest regression "
        "model to estimate State of Health (SOH) from voltage, "
        "current, temperature, and cycle number."
    )

    st.info(
        "This prototype uses simulated data. Its results do not "
        "establish real-world battery prediction accuracy or safety."
    )

except FileNotFoundError as error:

    st.error(
        "A required file could not be found. Make sure "
        "'battery_dataset.csv', 'battery_soh_model.pkl', "
        "and 'simulink_battery_data.csv' are in the "
        "application's working directory."
    )

    st.code(
        str(error)
    )

except Exception as error:

    st.error(
        "An error occurred while loading the dashboard."
    )

    st.code(
        str(error)
    )
